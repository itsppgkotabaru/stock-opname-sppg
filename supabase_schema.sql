create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text,
  role text not null default 'opname' check (role in ('admin','gudang','opname')),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id,email,role)
  values (new.id,new.email,'opname')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create table if not exists public.items (
  id bigint generated by default as identity primary key,
  code varchar(40) not null unique,
  name varchar(150) not null,
  category varchar(100),
  unit varchar(30) not null,
  min_stock numeric(14,3) not null default 0 check (min_stock >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.stock_transactions (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.items(id),
  txn_date date not null,
  txn_type text not null check (txn_type in ('masuk','keluar','penyesuaian_awal')),
  qty numeric(14,3) not null check (qty > 0),
  note varchar(255),
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now()
);
create index if not exists idx_stock_tx_date_item on public.stock_transactions(txn_date,item_id);

alter table public.profiles enable row level security;
alter table public.items enable row level security;
alter table public.stock_transactions enable row level security;

-- Kebijakan awal: seluruh pengguna yang sudah login dalam proyek ini dapat
-- membaca dan mengelola data bersama. Batasi kebijakan berdasarkan role sebelum
-- dipakai di lingkungan produksi jika hak akses berbeda diperlukan.
drop policy if exists "authenticated users can read profiles" on public.profiles;
create policy "authenticated users can read profiles" on public.profiles
for select to authenticated using (true);

drop policy if exists "authenticated users can read items" on public.items;
create policy "authenticated users can read items" on public.items
for select to authenticated using (true);
drop policy if exists "authenticated users can add items" on public.items;
create policy "authenticated users can add items" on public.items
for insert to authenticated with check (true);
drop policy if exists "authenticated users can update items" on public.items;
create policy "authenticated users can update items" on public.items
for update to authenticated using (true) with check (true);

drop policy if exists "authenticated users can read transactions" on public.stock_transactions;
create policy "authenticated users can read transactions" on public.stock_transactions
for select to authenticated using (true);
drop policy if exists "authenticated users can add transactions" on public.stock_transactions;
create policy "authenticated users can add transactions" on public.stock_transactions
for insert to authenticated with check (auth.uid() = created_by);

